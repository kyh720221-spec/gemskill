    s = s.replace(/(해|하여|해서|하는|할|하고|하기|해 주는|해주는|해 줄|해줄)$/, '').trim();
    s = s.replace(new RegExp(`\\s(${Object.keys(VERB_MAP).sort((a, b) => b.length - a.length).join('|')})$`), '').trim();
    s = s.replace(/(을|를|이|가)$/, '').trim();
