  function uniq(arr, prefixLen) {
    const seen = [];
    return arr.filter((s) => {
      const k = String(s || '').replace(/\s+/g, ' ').replace(/[.。]$/, '').trim();
      if (!k) return false;
      const dup = seen.some((x) => x === k || (prefixLen && k.length >= prefixLen && x.length >= prefixLen && (x.startsWith(k.slice(0, prefixLen)) || k.startsWith(x.slice(0, prefixLen)))));
      if (dup) return false;
      seen.push(k);
      return true;
    });
  }
