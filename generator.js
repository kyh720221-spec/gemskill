  function splitSentences(text) {
    return String(text || '')
      .replace(/\r/g, '')
      .replace(/([.!?。])\s+/g, '$1\n')
      .replace(/\s*[•▪‣]\s+/g, '\n')
      .replace(/(^|\n)\s*(?:[-*]|\d+[.)])\s+/g, '$1')
      .split(/\n+/)
      .map((s) => String(s || '').trim())
      .filter((s) => s.length > 1);
  }

